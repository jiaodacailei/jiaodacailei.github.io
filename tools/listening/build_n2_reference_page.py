# 同形异读词条（标题文字完全相同、括注读音不同）——词条音频文件名按 TTS 文本的
# hash 命名，文字相同就会共用同一个音频文件（读成哪个全看 TTS 猜）。按完整标题
# （含编号）指定各自喂给 TTS 的读音。第9单元：1221 出生（しゅっしょう）/1224 出生（しゅっせい）。
TTS_WORD_TEXT_BY_LABEL = {
    "1221. 出生（しゅっしょう）": "しゅっしょう",
    "1224. 出生（しゅっせい）": "しゅっせい",
}


def apply_tts_reading_overrides(text):
    if text in TTS_EXACT_TEXT_OVERRIDES:
        return TTS_EXACT_TEXT_OVERRIDES[text]
    for kanji, kana in TTS_READING_OVERRIDES.items():
        text = text.replace(kanji, kana)
    return text


def probe_duration(path):
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
        capture_output=True, text=True,
    )
    try:
        return round(float(r.stdout.strip()), 3)
    except ValueError:
        return None


def whisper_align(model, wav_path, text):
    segments, _ = model.transcribe(
        wav_path, language="ja", word_timestamps=True, beam_size=5,
        condition_on_previous_text=False,
    )
    words = []
    for seg in segments:
        if seg.words:
            words.extend(seg.words)
    if not words:
        return None
    _split, char_times_per_sentence, _edge_start, _edge_end = align_group(
        [{"text": text}], words, 0.0
    )
    if char_times_per_sentence is None:
        return None
    return char_times_per_sentence[0]


# 对齐缓存的落盘路径（main() 里设置）。全量重新对齐要几个小时（Whisper medium
# CPU 约 7 秒/句），曾经跑了 3 个多小时被系统因内存不足杀掉、缓存因为只在最后
# 一次性写盘而全部白费——所以每对齐 _ALIGN_SAVE_EVERY 句就原子写盘一次，被中断后
# 重跑只会重算最后不到 20 句。
_ALIGN_CACHE_PATH = None
_ALIGN_SAVE_EVERY = 20
_align_since_save = 0


def _save_align_cache(cache):
    if not _ALIGN_CACHE_PATH or cache is None:
        return
    tmp = _ALIGN_CACHE_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(cache, f, ensure_ascii=False)
    os.replace(tmp, _ALIGN_CACHE_PATH)


def synth_and_align(model, text, audio_dir, seg_id, tmp_wav, stats, cache=None):
    """合成+对齐一句话，返回(audio_rel_filename, duration, char_times)。
    已经合成过（音频文件已存在）就跳过TTS这一步。

    **文件名按TTS实际喂进去的文本内容算hash，不按seg_id位置命名**——真实
    反馈"为什么不是按内容存储相关音频名字"：以前文件名直接是`seg-{seg_id:
    03d}.mp3`，`seg_id`是这句在整个内容模块里的数组位置。往已有词条中间
    插入一条新例句（哪怕只是给某个词条补一条漏收的例句）会让它后面所有
    句子的`seg_id`集体后移一位，但磁盘上老的`seg-042.mp3`这个文件名还在、
    还能通过`os.path.exists()`判断，脚本会误以为"这句已经合成过"直接跳过
    TTS，实际把错误的旧音频当成新位置那句话的音频用——这正是本skill文档
    "给已有词条追加例句，把整个音频缓存全部搅乱了"那次事故的根因。改成
    对`apply_tts_reading_overrides(text)`（TTS真正合成的那份文本，不是
    合成前的原文——这样`TTS_READING_OVERRIDES`订正表变了也会自动令旧文件
    失效，不需要手动删）算一次sha1取前12位hex当文件名主体，同一句话不管
    挪到数组哪个位置、insert在哪个词条中间，hash都不变，天然免疫这类位置
    错位——以后插入/编辑已有词条的例句不再需要整批删audio目录重新合成，
    只有文本真的变了的那几句会重新触发TTS。

    对齐结果按内容hash+音频文件mtime存进一份JSON缓存（`cache`参数，
    load/save在main()里做），命中缓存就直接复用旧的char_times，不用每次
    全量重新跑一遍whisper——这条原来的设计是"每次都现算，不维护缓存"
    （理由是"faster-whisper跑一句几秒钟，量级上不需要省这个"），词汇页
    句子数从最初的206条涨到515条之后，这个假设不再成立：单改一两个词的
    读音，也要陪跑全部515句的whisper对齐，实测一次要花十几到二十分钟。
    真实反馈"是不是搞错了"/"只需要比对出错的即可哟"——用户直接指出了这个
    效率问题。mtime而不是文件内容hash判断"音频有没有变"：这个场景下音频
    要么原封不动、要么整个被删除重新合成（没有"内容悄悄变了但mtime没变"
    这种中间状态），mtime足够可靠且不用读整个文件再算一遍哈希。"""
    tts_text = apply_tts_reading_overrides(text)
    content_hash = hashlib.sha1(tts_text.encode("utf-8")).hexdigest()[:12]
    filename = f"seg-{content_hash}.mp3"
    out_path = os.path.join(audio_dir, filename)
    if not os.path.exists(out_path):
        try:
            synth_tts(tts_text, out_path)
        except Exception as e:
            print(f"[id={seg_id}] TTS FAILED: {e}")
            stats["failed"] += 1
            return None, None, None

    mtime = os.path.getmtime(out_path)
    # 缓存现在纳入版本管理（audio/.align_cache.json），所以"音频有没有变"改按音频
    # 内容的 sha1 判断——git clone/checkout 会改写 mtime，只认 mtime 的话换一台机器
    # 或重新检出之后缓存全部失效，又要重算几个小时。向后兼容：旧缓存条目没有 sha1，
    # 退回比 mtime，命中后补上 sha1。
    with open(out_path, "rb") as _af:
        audio_sha = hashlib.sha1(_af.read()).hexdigest()
    cache_key = content_hash
    if cache is not None:
        cached = cache.get(cache_key)
        if cached and cached.get("text") == text and (
            cached.get("sha1") == audio_sha
            or (cached.get("sha1") is None and cached.get("mtime") == mtime)
        ):
            cached["sha1"] = audio_sha
            stats["cached"] = stats.get("cached", 0) + 1
            return filename, cached["duration"], cached["char_times"]

    duration = probe_duration(out_path)
    subprocess.run(
        ["ffmpeg", "-y", "-i", out_path, "-ar", "16000", "-ac", "1", tmp_wav],
        capture_output=True,
    )
    char_times = whisper_align(model, tmp_wav, text)
    if char_times is None:
        stats["fallback"] += 1
        n = len(text)
        if duration and n > 0:
            char_times = [round(duration * k / n, 2) for k in range(n)]
    else:
        stats["ok"] += 1
    if cache is not None:
        cache[cache_key] = {
            "text": text, "mtime": mtime, "sha1": audio_sha,
            "duration": duration, "char_times": char_times,
        }
        global _align_since_save
        _align_since_save += 1
        if _align_since_save >= _ALIGN_SAVE_EVERY:
            _align_since_save = 0
            _save_align_cache(cache)
    return filename, duration, char_times


_WORD_NUM_PREFIX_RE = re.compile(r"^\d+[a-z]?\.\s*")
_WORD_TRAILING_FULLWIDTH_PAREN_RE = re.compile(r"（[^（）]*）$")
_TITLE_LEADING_NUM_RE = re.compile(r"^(\d+)[a-z]?\.")


def title_number(title):
    """从标题开头抽出书本原始印刷编号（比如"0012. 上がる（あがる）"抽出
    12）——真实反馈"所有单词的序号要和原文对上"：书本编号必须逐字照抄，
    但`UNITS`/`points`数组本身的顺序不强制要求跟书本一致（数组顺序决定
    `word_id`/`seg_id`分配、进而决定音频文件名，一旦改变数组顺序就等于
    让所有音频文件名跟内容重新对应一遍，必须整批重新合成——用户明确
    表示"只改编号，页面展示时按照编号排序即可"，不要求真的重排数组）。
    这个函数只用于"页面展示顺序"（`main()`里给最终的`questions`列表
    排序、`build_vocab_quiz_items()`里给"组N"分类计算书本序次），不影响
    `word_id`/`seg_id`分配——那两处分配始终按`unit["points"]`数组自己
    的原始顺序来，跟这个函数完全无关。找不到编号前缀时返回一个很大的
    数字垫底，不会让格式异常的标题排到最前面把正常顺序搅乱。"""
    m = _TITLE_LEADING_NUM_RE.match(title)
    return int(m.group(1)) if m else 10**9


def word_answer_text(title):
    """从标题原文抽出"这个词/语法点本身该怎么读"——跟 listening-page.js
    里 extractTitleAnswer() 完全同一条规则（去掉编号前缀，去掉结尾的全角
    括注），两处独立各写一份是因为一个跑在Python构建期、一个跑在浏览器里，
    没有共享模块的机制，规则改动要记得两边一起改。"""
    return _WORD_TRAILING_FULLWIDTH_PAREN_RE.sub(
        "", _WORD_NUM_PREFIX_RE.sub("", title)
    ).strip()


def synth_word_audio(text, audio_dir, word_id, stats):
    """给词条/语法点标题本身合成一份"单独读这个词"的音频——跟例句音频是
    两回事：例句要跟读高亮，得跑whisper对齐拿char_times；这个只是点一下
    听发音，不需要逐字时间戳，纯TTS，省掉对齐这一步（不需要model/tmp_wav
    参数）。文件名前缀"word-"跟例句的"seg-"分开一套独立编号，不共用同一个
    计数器——例句以后可能因为某条目新增/去掉某句例句而不再对齐，词audio
    的编号只跟"点"的出现顺序有关，两套编号各自独立递增，互不干扰。

    跟`synth_and_align()`同一条"按内容hash命名，不按位置命名"规则——文件名
    主体是对`apply_tts_reading_overrides(text)`算的sha1前12位，不是
    `word_id`，理由同样是"中途插入/删除词条会让word_id集体错位，位置命名
    会导致旧文件被误判成新词条已经合成过"。"""
    tts_text = apply_tts_reading_overrides(text)
    content_hash = hashlib.sha1(tts_text.encode("utf-8")).hexdigest()[:12]
    filename = f"word-{content_hash}.mp3"
    out_path = os.path.join(audio_dir, filename)
    if not os.path.exists(out_path):
        try:
            synth_tts(tts_text, out_path)
        except Exception as e:
            print(f"[word_id={word_id}] 单词发音TTS FAILED: {e}")
            stats["word_failed"] = stats.get("word_failed", 0) + 1
            return None
    return filename


def build_point_sentences(units, model, audio_dir, tmp_wav, stats, mondai_label, cache=None):
    """把 UNITS 展开成 build_lesson_data() 要的 (sentences, questions) 扁平
    列表——跟 l17/l18"语法与表达"tab 的数据形状完全一致，每个语法点/单词
    条目是一个"question"，它的例句是这个question底下的sentences。

    一个语法点如果有多个接续（`point["groups"]`，见脚本开头docstring），
    每组自己的例句照样走seg_id全局递增+TTS/对齐这一套（组与组之间共用
    同一个计数器，不是各自从1开始），只是额外把每组的seg_id列表记进
    `question["groups"]`（`[{"overview": 这组自己的文字, "ids": [seg_id,...]}]`），
    供 build_lesson_data() 按组切分渲染，而不是像普通点那样直接平铺进
    `sentences`。没有 groups 的点完全不受影响，走原来的逻辑。

    额外返回一份 `word_audio_by_id`（{word_id: 实际合成出的文件名}）——
    `build_vocab_quiz_items()` 也要给"单词测试"tab标注音频文件名，以前是
    独立重新推导一遍`word_tts_text`（跟这里`derive_reading()`那套判断
    逻辑重复一份），现在文件名已经改成按内容hash而不是`word_id`命名，
    两处各自独立算hash必须保证用的是完全同一份`word_tts_text`才不会算出
    不同的hash——两份逻辑分开维护、后续任何一边改了判断条件都很容易只改
    一处漏改另一处。改成这里算好的文件名直接传出去、`build_vocab_quiz_
    items()`只管拿来用，不重新推导，从根上消除"两处独立重建必须保持一致"
    这个维护负担。

    `point["pitch"]`（词汇页专属，语法点没有这个字段，`point.get("pitch",
    "")`对语法点始终是空字符串，不影响语法页）——真实反馈"原文中是标了
    音高的小数字1-5等的，但是本项目中都漏掉了"：书上每个词条在读音括注
    后面、词性标签前面还印着①～⑤这类圈起来的数字（日语词典标准的"音调
    核"标记，不是编号，也不影响TTS怎么读——edge-tts不支持按这种标记调
    音高，这里纯粹是给学习者看的参考信息），转录时一直没收录这个字段。
    `pitch`存的是原文这个位置印的圈码原样拼接的字符串（比如单一读音配
    单一音高是"①"，一个词有两种写法各自配一个音高比如"アイデア/
    アイディア（idea）③①"存"③①"，同一写法有多个合法音高比如"青白い
    （あおじろい）①④"也是存"①④"——不强行拆分成"每种写法对应哪个数字"
    这种结构化关系，逐字照抄原文这个位置印的内容就够，跟这份内容模块
    "严禁改写/编造、只能照抄"的一贯原则一致）。不写进`title`字符串本身
    （虽然书上物理位置是在`title`里"（读音）"和"[词性]"之间），是因为
    `title`这个字符串被好几处正则依赖（`word_answer_text()`/
    `derive_reading()`/默写模式的`extractTitleAnswer()`……），插入这个
    圈码会打乱"结尾必须是全角括注"这类假设——单开一个字段，
    `page-renderer.js`渲染时再拼回视觉上"词（读音）音高[词性]"这个书本
    原有顺序，两边各自负责"数据该长什么样"和"展示该长什么样"，不用互相
    迁就对方的解析逻辑。"""
    sentences = []
    questions = []
    word_audio_by_id = {}
    seg_id = 0
    word_id = 0

    def synth_examples(examples, question_label):
        nonlocal seg_id
        ids = []
        for example in examples:
            ja, zh = example[0], example[1]
            blanks = example[2] if len(example) > 2 else []
            seg_id += 1
            filename, duration, char_times = synth_and_align(
                model, ja, audio_dir, seg_id, tmp_wav, stats, cache
            )
            if filename is None:
                continue
            sentences.append({
                "id": seg_id, "mondai": mondai_label, "question": question_label,
                "text": ja, "zh": zh, "notes": "", "blanks": blanks,
                "start": 0.0, "char_times": char_times, "audio_file": filename,
            })
            ids.append(seg_id)
        return ids

    for unit in units:
        unit_label = unit.get("label", "")
        for point in unit["points"]:
            question_label = point["title"]
            word_id += 1
            word_text = word_answer_text(question_label)
            # 词条标题本身带"/"或"／"（一个词两种写法，比如"暖か/温か"）时，
            # 不能把这段原样喂给TTS——真实反馈"暖か/温か的发音是
            # atatakanaatataka，应该是atataka吧"：TTS会把两种写法都当成
            # 独立文字念一遍，读成"两遍读音拼在一起"，不是"/"本身被念出来
            # 那么简单。这种情况改喂derive_reading()已经推导出的那份唯一
            # 权威读音（对这条就是纯假名"あたたか"），跟着音发音不会有歧义；
            # 没有"/"的词条不受影响，继续用原来的word_text（保留汉字喂给
            # TTS，让它自己按汉字选读音，多音字读错的个例走
            # TTS_READING_OVERRIDES单独订正，不在这里放大整改范围）。
            #
            # 词条本身只有一种写法、但结尾括注里标了多个"/"或"／"分隔的读音
            # （比如"～位（～い／～くらい）"、"行き（いき／ゆき）"——书上自己
            # 承认这个词有歧义读音）也要走derive_reading()喂纯假名，不能只看
            # word_text本身有没有斜杠——真实反馈"单词测试答案不对，应该是
            # kana才对"揪出的是quiz_kana字段的同一类bug（derive_reading()
            # 自己判断"整个括注是不是纯假名"时被"／"分隔符干扰误判，已经在
            # derive_reading()内部修过），这里的word_tts_text是分开维护的
            # 另一份判断，那次修复没有覆盖到——用edge-tts实测两个词当时凑巧
            # 蒙对了正确读音（"～位"读出い、"行き"读出いき，都是括注里排在
            # 第一位的读音，едge-tts自己按汉字猜出来的，不是这段代码保证的），
            # 不是真的没问题，只是运气好没暴露；不加这条判断，以后遇到运气
            # 不好的同类词条会真的读错。
            _paren_m = _TRAILING_PAREN_CONTENT_RE.search(_WORD_NUM_PREFIX_RE.sub("", question_label))
            _paren_has_multi_reading = bool(_paren_m) and ("/" in _paren_m.group(1) or "／" in _paren_m.group(1))
            word_tts_text = derive_reading(question_label, word_text) if (
                "/" in word_text or "／" in word_text or _paren_has_multi_reading
            ) else word_text
            # 标题带汉字、括号里是单一纯假名读音（"雄（おす）""～下（～か）"）时，
            # 直接把括号里的读音喂给TTS，不让它对孤立汉字/前后缀猜读音——以前只
            # 靠TTS_EXACT_TEXT_OVERRIDES逐个补，真实反馈"后面不是有kana吗？为啥
            # 还读错？"。多读音/斜杠/英文词源括注的词条不走这条，保持原逻辑。
            if word_tts_text == word_text and not _KANA_ONLY_RE.match(word_text):
                if _paren_m and _KANA_ONLY_RE.match(_paren_m.group(1)):
                    word_tts_text = _paren_m.group(1).replace("～", "").replace("・", "") or word_tts_text
            word_tts_text = TTS_WORD_TEXT_BY_LABEL.get(question_label, word_tts_text)
            word_audio = synth_word_audio(word_tts_text, audio_dir, word_id, stats) if word_text else None
            word_audio_by_id[word_id] = word_audio
            groups = point.get("groups")
            if groups:
                group_meta = [
                    {"overview": g.get("overview", ""),
                     "ids": synth_examples(g["examples"], question_label)}
                    for g in groups
                ]
                questions.append({
                    "mondai": mondai_label, "question": question_label,
                    "overview": "\n\n".join(g.get("overview", "") for g in groups),
                    "answer": "", "unit": unit_label, "wordAudio": word_audio,
                    "pitch": point.get("pitch", ""),
                    "groups": group_meta,
                })
            else:
                synth_examples(point["examples"], question_label)
                qrec = {
                    "mondai": mondai_label, "question": question_label,
                    "overview": point.get("overview", ""), "answer": "",
                    "unit": unit_label, "wordAudio": word_audio,
                    "pitch": point.get("pitch", ""),
                }
                # N2词汇页专属（"senses"字段是这次overview结构化改造引入的，
                # 只有词汇内容模块有，语法点没有）：把"单词测试"tab现算7种
                # 题型需要的全部原始事实（text/kana/senses/variants/
                # related）一起写进这同一个question对象里，不再由
                # build_vocab_quiz_items()另外产出一份独立的quiz_data数组
                # 塞进单独的<script id="vocab-quiz-data">——真实反馈"前端只要
                # 拿到基础数据，自己就可以生成题目数据，为啥要单独存一份"。
                # senses本身已经是结构化数据，不需要在这里现算zh/zhVariants
                # 文本再传过去（那样又会重新引入"JS 端反过来解析文本猜结构"
                # 这个刚刚才消灭掉的坏模式）——page-renderer.js里的
                # deriveQuizWordsFromTabs()直接读senses数组自己拼zh/
                # zhVariants，是纯数组join，不涉及任何正则/文本解析。
                # variants（多写法/多读音）继续留在Python算（derive_reading_
                # variants()本身是从title字符串正则解析出来的，这条解析逻辑
                # 已经跑了很久、行为稳定，没必要在JS里重新维护一份同样脆弱的
                # 正则，直接把算好的结果当成词条自己的一个事实字段传过去）。
                if "senses" in point:
                    variants = derive_reading_variants(question_label, word_text)
                    qrec["kana"] = derive_reading(question_label, word_text)
                    qrec["text"] = word_text
                    qrec["senses"] = point["senses"]
                    if len(variants) > 1:
                        qrec["variants"] = variants
                    if point.get("related"):
                        qrec["related"] = point["related"]
                questions.append(qrec)
    return sentences, questions, word_audio_by_id


_TRAILING_PAREN_CONTENT_RE = re.compile(r"（([^（）]*)）$")
_KANA_ONLY_RE = re.compile(r"^[぀-ゟ゠-ヿー・～]+$")


def derive_reading(title, word_text):
    """给"单词测试"tab的audio2kana/zh2kana两道题型推读音——词条标题结尾的
    全角括注，如果整段内容本身就是纯假名（"（あいかわらず）"这种），那就是
    读音；如果不是纯假名（"（iron）"这种英文词源提示，不是读音），说明这个
    词本身已经是假名了（外来语片假名词自己就能读，标题结尾的英文纯粹是
    给人看词源用的），读音就是word_text本身。"多个写法用"/"或"／"分隔"
    （"アイデア/アイディア"半角、"いざとなると／いざとなれば／
    いざとなったら"全角，两种都出现过）这种取第一个当权威读音，不需要
    全部都收——真实反馈"0118. いざとなると／いざとなれば／いざとなったら"
    这条audio2kana/zh2kana的答案检查发现，之前只按半角"/"切分，这条词
    整段没有末尾读音括注（本身已经是纯假名，不需要另外标注读音）又用的是
    全角"／"分隔三种写法，两次判断都没生效，"kana"直接变成了三种写法
    原样拼在一起的完整字符串，用户不可能打对这种答案。改成同时按半角/
    全角两种斜杠切分，不区分标题实际用的是哪一种。

    **先判断word_text自己是不是已经纯假名**：外来语标题（"アポ"这种）
    需要优先直接用word_text本身当答案，不能先看括注——真实案例"0046.
    アポ（アポイントメント／appointment）"，括注里的"アポイントメント"
    是给人看的全称/词源提示，不是"アポ"这个词自己的读音，如果不先判断
    word_text本身已经是假名就直接进括注分支，会把答案错误地写成
    "アポイントメント"而不是词条本身的"アポ"。

    **括注内容如果带"/"或"／"，要先按分隔符切出第一段，再判断这一段是不是
    纯假名**，不能对整个括注原文做纯假名判断——真实案例"0091. ～位
    （～い／～くらい）"：括注原文"～い／～くらい"整体因为中间夹着全角
    斜杠，判定不是纯假名，导致整个函数跳过括注、退回到word_text分支，
    但word_text是"～位"（词本身，不含斜杠），最终"kana"字段被错误地存成
    了"位"这个汉字本身——真实反馈"单词测试答案不对，应该是kana才对"。
    先切分括注内容再逐段判断纯假名，才能在"アポ"（word_text本身已是
    假名，不看括注）和"～位"（word_text带汉字，要看括注，括注还要再切
    一次取第一个读音）这两类真实场景下都给出正确答案。"""
    first_word_form = re.split(r"[/／]", word_text)[0].strip("～")
    if _KANA_ONLY_RE.match(first_word_form):
        return first_word_form
    m = _TRAILING_PAREN_CONTENT_RE.search(_WORD_NUM_PREFIX_RE.sub("", title))
    if m:
        candidate = re.split(r"[/／]", m.group(1))[0]
        if _KANA_ONLY_RE.match(candidate):
            return candidate
    return first_word_form


def derive_reading_variants(title, word_text):
    """返回这个词条标题隐含的全部"写法+读音"组合，供"单词测试"按写法/读音
    分别出题用——真实反馈"这种需要出三道日-中题，中-日也是三道……这种日中
    两道题，日kana两道题……这种日kana两道题"，给了三个真实例子：
    ①"暖か/温か（あたたか）"（2种写法，共用1个读音）该出2道"根据日文写
    中文"+2道"根据日文写假名"（各写法各配自己的题面）；②"行き（いき／
    ゆき）"（1种写法，2个读音）该出2道"根据日文写假名"；③"いざとなると／
    いざとなれば／いざとなったら"（3种写法、每种写法本身就是自己的假名，
    没有额外读音）该出3道"根据日文写中文"+3道"中文写假名"（中文题面相同，
    答案不同，需要在题面上加①②③这类小标记区分是哪一种写法）。

    没有"/"或"／"的普通词条返回长度为1的列表，跟`derive_reading()`单一
    结果一致，调用方（`build_vocab_quiz_items()`）不需要对"有没有变体"
    分支特殊处理。

    三种真实形态的判断规则：
    - `word_text`本身有多个"/"或"／"分隔的写法**且**结尾括注是单一的纯
      假名读音 → 每种写法各自配这同一个共享读音（暖か/温か型）。
    - `word_text`本身有多个写法**但没有**括注给出共享读音（纯假名的多种
      口语变体，比如"いざとなると／…"本身就没有额外的读音括注）→ 每种
      写法各自的读音就是它自己（因为这几种写法本身已经是纯假名）。
    - `word_text`只有一种写法，但结尾括注本身用"/"或"／"分隔了多个读音
      → 同一种写法配多个不同读音（行き型）。
    以上都不满足时退回`derive_reading()`的单一结果，包一层长度为1的列表。
    """
    m = _TRAILING_PAREN_CONTENT_RE.search(_WORD_NUM_PREFIX_RE.sub("", title))
    paren_readings = []
    if m:
        paren_readings = [r for r in re.split(r"[/／]", m.group(1)) if _KANA_ONLY_RE.match(r)]
    # 注意：这里不能像 derive_reading() 的 first_word_form 那样 strip("～")——
    # 那边只是为了判断"这段本身是不是纯假名"，不影响它自己不对外暴露的
    # 中间值；这里的 text 是要直接显示给用户看的题面（"根据日文写中文"
    # 这类题目的日文原文），"～位"这种前缀式词条必须保留"～"才是书上印的
    # 原样写法，strip 掉会变成"位"，看起来像是另一个词。
    texts = [t for t in re.split(r"[/／]", word_text) if t]
    if len(texts) > 1:
        if paren_readings:
            shared_kana = paren_readings[0]
            return [{"text": t, "kana": shared_kana} for t in texts]
        return [{"text": t, "kana": t} for t in texts]
    if len(paren_readings) > 1:
        return [{"text": texts[0], "kana": r} for r in paren_readings]
    return [{"text": texts[0] if texts else word_text, "kana": derive_reading(title, word_text)}]


_QUIZ_ZH_POS_LINE_RE = re.compile(r"^\s*[\[［][^\]］]*[\]］]")


def render_sense_line(sense):
    """把一个结构化 sense（{"pos", "groups":[[近义说法,...],...]}）拼成
    跟旧版overview第一行完全相同形状的字符串——"[词性] 义项1；义项2"，
    组内近义说法用逗号连接。这是`senses`字段唯一的展示格式，`quiz_zh_
    text()`/`derive_meaning_variants()`/`render_overview()`三处共用，
    保证"根据单词写中文意思"题面、"词性选择"题的`[词性]`标签、生词卡片
    展示的overview文字三者永远读的是同一份数据、不会互相走样。"""
    body = "；".join("，".join(g) for g in sense["groups"])
    return f"[{sense['pos']}] {body}"


def quiz_zh_text(point):
    """"单词测试"tab要用的中文释义——第一个 sense 拼成的字符串。**保留
    开头的"[词性]"标签，不剥离**——跟教材课`build_vocab_quiz_data.py`的
    `entry["zh"] = w["zh"]`一样直接透传原文，两边数据格式保持一致。这个
    字段早期版本会剥掉标签（当时只有ja2zh/zh2kana两道题型要用这个字段，
    标签确实不算释义内容），后来"单词测试"新增第5种题型"词性选择"
    （`listening-page.js`的`posFor()`），要从`zh`字段开头现取这个标签当
    正确答案——真实反馈"N2词汇的单词测试中，为什么没有词性选择题"，查
    下来就是这里在生成时把标签提前剥掉了，跟教材课的数据格式不一致，
    `posFor()`找不到标签，判定"这个词没有词性标注"直接跳过，422个词条
    全军覆没。ja2zh/zh2kana判分时前端会自己剥掉标签再比较（`listening-
    page.js`的`POS_RE`/`zhSegments()`），数据这一层保留标签不影响这两道
    题原有的判分逻辑。

    N2词汇内容模块（`n2_vocab_content.py`）现在直接提供结构化的`senses`
    字段（见《N2词汇overview结构化-设计文档.md》），不再需要从`overview`
    自由文本里用正则猜"哪一行是独立义项"——`senses`本身就是显式的义项
    列表，`quiz_zh_text()`只需要取第一个sense拼成字符串。N2语法内容模块
    （`n2_grammar_content.py`）还没有迁移到这套结构，`point`没有`senses`
    字段时退回旧版"读overview第一行"逻辑，两边共用同一个入口函数。"""
    senses = point.get("senses")
    if senses:
        return render_sense_line(senses[0])
    first_line = (point.get("overview") or "").split("\n")[0]
    return first_line.strip()


def derive_meaning_variants(point):
    """跟`derive_reading_variants()`同一类问题，但轴不一样——这里是"一个词
    条在书上标了不止一个独立义项"（比如"0147. 一層"：`senses`第一项
    {"pos":"名","groups":[["一层","一楼"]]}，第二项{"pos":"副","groups":
    [["更","更加","越发"]]}，是两个词性各自独立的意思，不是同一个词性下
    用顿号并列的近义释义），`quiz_zh_text()`只取第一个sense会让第二个
    义项在"单词测试"里彻底从数据层面消失——不只是"根据单词写中文意思"
    答不出第二个意思，"根据中文写假名"的题面也永远不会用第二个意思出题。
    真实反馈"一層的中文有两个一个名词，一个副词，但是单词测试中，只有
    一个名词，副词的答案漏掉了"。

    `senses`长度>1时才当作"这个词真的有多个独立义项"，返回长度>1的
    列表；只有1个sense（绝大多数词条）退回`quiz_zh_text()`的单一结果，
    包一层长度为1的列表，调用方（`build_vocab_quiz_items()`）不需要对
    "有没有多义项"分支特殊处理。`point`没有`senses`字段（N2语法内容
    模块）时退回旧版"按行首[词性]格式扫描overview"逻辑。"""
    senses = point.get("senses")
    if senses:
        if len(senses) > 1:
            return [render_sense_line(s) for s in senses]
        return [quiz_zh_text(point)]
    overview = point.get("overview") or ""
    lines = [l.strip() for l in overview.split("\n") if l.strip()]
    pos_lines = [l for l in lines if _QUIZ_ZH_POS_LINE_RE.match(l)]
    if len(pos_lines) > 1:
        return pos_lines
    return [quiz_zh_text(point)]


def chunk_group_sizes(n, size=10, min_last=5):
    """跟 build_exam_vocab.py 的同名函数完全一样的算法（这里独立复制一份，
    两个脚本没有共享模块的机制）：把n个词按size一组切页，最后一组如果
    小于min_last就并进上一组。真实反馈"如果最后一组少于5个，就合到上一组
    吧"——先在N2真题模考的单词测试分类上用过一次，这次是"单词测试"分类
    和侧栏导航分组（page-renderer.js里的chunkGroupSizes，JS单独一份）
    两个新场景复用同一条规则。"""
    if n <= 0:
        return []
    if n <= size:
        return [n]
    full, rem = divmod(n, size)
    if rem == 0:
        return [size] * full
    if rem < min_last:
        return [size] * (full - 1) + [size + rem]
    return [size] * full + [rem]


